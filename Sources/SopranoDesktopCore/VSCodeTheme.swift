import Foundation

/// The Soprano colour-theme extension for VS Code and Cursor (both install the same `.vsix`).
///
/// The extension contributes `Soprano Light` and `Soprano Dark`; each theme's base (`vs` or
/// `vs-dark`) follows its palette's appearance, so a pinned dark pair yields two dark themes.
public enum VSCodeTheme {
    public static let publisher = "soprano"
    public static let extensionName = "soprano-theme"
    public static var extensionID: String { "\(publisher).\(extensionName)" }

    static let displayName = "Soprano"
    static let description = "Soprano Light and Soprano Dark, generated by Soprano Desktop from Soprano's themes."
    static let engine = "^1.70.0"

    static func themePath(slug: String) -> String {
        "themes/\(slug)-color-theme.json"
    }

    /// Every member of the .vsix archive, paths relative to the archive root:
    /// "[Content_Types].xml", "extension.vsixmanifest", "extension/package.json",
    /// "extension/themes/soprano-light-color-theme.json", "extension/themes/soprano-dark-color-theme.json".
    public static func packageFiles(for pair: ThemePair, version: String) -> [GeneratedFile] {
        [
            GeneratedFile(path: "[Content_Types].xml", contents: contentTypes),
            GeneratedFile(path: "extension.vsixmanifest", contents: vsixManifest(version: version)),
            GeneratedFile(path: "extension/package.json", contents: packageJSON(for: pair, version: version)),
            GeneratedFile(
                path: "extension/" + themePath(slug: ThemeNames.lightSlug),
                contents: colorTheme(for: pair.light, name: ThemeNames.light)
            ),
            GeneratedFile(
                path: "extension/" + themePath(slug: ThemeNames.darkSlug),
                contents: colorTheme(for: pair.dark, name: ThemeNames.dark)
            ),
        ]
    }

    /// One VS Code colour theme JSON document.
    public static func colorTheme(for palette: Palette, name: String) -> String {
        let syntax = SyntaxPalette(palette)
        return json([
            "$schema": "vscode://schemas/color-theme",
            "name": name,
            "type": palette.isLight ? "light" : "dark",
            "semanticHighlighting": true,
            "colors": colors(for: palette, syntax: syntax),
            "tokenColors": tokenColors(for: syntax),
            "semanticTokenColors": semanticTokenColors(for: syntax),
        ])
    }

    // MARK: - Package

    static func packageJSON(for pair: ThemePair, version: String) -> String {
        func theme(_ palette: Palette, label: String, slug: String) -> [String: Any] {
            ["label": label, "uiTheme": palette.isLight ? "vs" : "vs-dark", "path": "./" + themePath(slug: slug)]
        }
        return json([
            "name": extensionName,
            "displayName": displayName,
            "description": description,
            "publisher": publisher,
            "version": version,
            "engines": ["vscode": engine],
            "categories": ["Themes"],
            "contributes": [
                "themes": [
                    theme(pair.light, label: ThemeNames.light, slug: ThemeNames.lightSlug),
                    theme(pair.dark, label: ThemeNames.dark, slug: ThemeNames.darkSlug),
                ],
            ],
        ])
    }

    /// The Open Packaging Conventions content-type map `vsce` writes at the archive root.
    static let contentTypes = """
        <?xml version="1.0" encoding="utf-8"?>
        <Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\
        <Default Extension=".json" ContentType="application/json"/>\
        <Default Extension=".vsixmanifest" ContentType="text/xml"/>\
        </Types>

        """

    /// The VSIX 2.0 package manifest, in the shape `vsce package` writes.
    static func vsixManifest(version: String) -> String {
        """
        <?xml version="1.0" encoding="utf-8"?>
        <PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011" xmlns:d="http://schemas.microsoft.com/developer/vsx-schema-design/2011">
          <Metadata>
            <Identity Language="en-US" Id="\(xmlEscaped(extensionName))" Version="\(xmlEscaped(version))" Publisher="\(xmlEscaped(publisher))" />
            <DisplayName>\(xmlEscaped(displayName))</DisplayName>
            <Description xml:space="preserve">\(xmlEscaped(description))</Description>
            <Tags>theme,color-theme</Tags>
            <Categories>Themes</Categories>
            <GalleryFlags>Public</GalleryFlags>
            <Properties>
              <Property Id="Microsoft.VisualStudio.Code.Engine" Value="\(xmlEscaped(engine))" />
              <Property Id="Microsoft.VisualStudio.Code.ExtensionDependencies" Value="" />
              <Property Id="Microsoft.VisualStudio.Code.ExtensionPack" Value="" />
              <Property Id="Microsoft.VisualStudio.Code.ExtensionKind" Value="ui,workspace,web" />
              <Property Id="Microsoft.VisualStudio.Code.LocalizedLanguages" Value="" />
            </Properties>
          </Metadata>
          <Installation>
            <InstallationTarget Id="Microsoft.VisualStudio.Code" />
          </Installation>
          <Dependencies />
          <Assets>
            <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json" Addressable="true" />
          </Assets>
        </PackageManifest>

        """
    }

    static func xmlEscaped(_ text: String) -> String {
        text
            .replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
            .replacingOccurrences(of: "'", with: "&apos;")
    }

    static func json(_ object: Any) -> String {
        // Only ever called with string/number/bool dictionaries and arrays, which always serialize.
        let data = try! JSONSerialization.data(
            withJSONObject: object,
            options: [.sortedKeys, .prettyPrinted, .withoutEscapingSlashes]
        )
        return String(decoding: data, as: UTF8.self) + "\n"
    }

