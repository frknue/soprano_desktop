    // MARK: - Syntax

    static func tokenColors(for s: SyntaxPalette) -> [[String: Any]] {
        func rule(_ name: String, _ scopes: [String], _ color: RGB?, style: String? = nil) -> [String: Any] {
            var settings: [String: Any] = [:]
            if let color { settings["foreground"] = color.hex }
            if let style { settings["fontStyle"] = style }
            return ["name": name, "scope": scopes, "settings": settings]
        }
        return [
            rule("Comment", ["comment", "punctuation.definition.comment", "string.comment"], s.comment, style: "italic"),
            rule("Variable", [
                "variable", "variable.other", "variable.other.readwrite", "variable.parameter",
                "meta.definition.variable.name",
            ], s.variable),
            rule("Keyword", [
                "keyword", "keyword.control", "keyword.other", "storage", "storage.type", "storage.modifier",
                "keyword.operator.new", "keyword.operator.expression", "keyword.operator.logical.python",
                "keyword.operator.wordlike", "variable.language", "support.type.primitive.ts",
            ], s.keyword),
            rule("Operator", ["keyword.operator", "punctuation.separator.key-value"], s.operator),
            rule("Punctuation", [
                "punctuation", "meta.brace", "punctuation.separator", "punctuation.terminator",
                "punctuation.accessor", "punctuation.definition.tag", "punctuation.section",
                "punctuation.definition.list.begin.markdown",
            ], s.punctuation),
            rule("String", [
                "string", "string.quoted", "string.template", "string.unquoted",
                "punctuation.definition.string", "markup.inline.raw", "markup.fenced_code", "markup.raw",
            ], s.string),
            rule("Constant", [
                "constant", "constant.numeric", "constant.language", "constant.character", "constant.other",
                "support.constant", "variable.other.constant", "variable.other.enummember",
                "entity.name.constant", "support.constant.property-value",
            ], s.constant),
            rule("Escape and regex", [
                "constant.character.escape", "string.regexp", "constant.other.placeholder",
                "constant.character.format.placeholder", "punctuation.definition.template-expression",
                "punctuation.section.embedded",
            ], s.special),
            rule("Function", [
                "entity.name.function", "support.function", "variable.function", "meta.function-call.generic",
                "entity.name.function.macro", "support.function.builtin",
            ], s.function),
            rule("Type", [
                "entity.name.type", "entity.name.class", "entity.name.struct", "entity.name.enum",
                "entity.name.interface", "entity.name.namespace", "entity.name.type.module",
                "entity.other.inherited-class", "support.type", "support.class", "storage.type.primitive",
                "storage.type.built-in", "entity.name.type.parameter",
            ], s.type),
            rule("Property", [
                "variable.other.property", "variable.other.object.property", "support.variable.property",
                "meta.object-literal.key", "support.type.property-name", "entity.name.tag.yaml",
                "variable.other.member",
            ], s.property),
            rule("Tag", ["entity.name.tag", "support.class.component", "meta.tag.sgml"], s.tag),
            rule("Attribute", [
                "entity.other.attribute-name", "meta.decorator", "punctuation.decorator",
                "entity.name.function.decorator", "storage.type.annotation", "meta.attribute",
                "storage.type.attribute",
            ], s.attribute),
            rule("Invalid", ["invalid", "invalid.illegal"], s.error),
            rule("Deprecated", ["invalid.deprecated"], s.warning, style: "strikethrough"),
            rule("Markup heading", ["markup.heading", "entity.name.section", "markup.heading.setext"], s.function, style: "bold"),
            rule("Markup bold", ["markup.bold"], nil, style: "bold"),
            rule("Markup italic", ["markup.italic"], nil, style: "italic"),
            rule("Markup strikethrough", ["markup.strikethrough"], nil, style: "strikethrough"),
            rule("Markup link", ["markup.underline.link", "string.other.link"], s.info, style: "underline"),
            rule("Markup quote", ["markup.quote"], s.comment, style: "italic"),
            rule("Inserted", ["markup.inserted", "punctuation.definition.inserted", "meta.diff.header.to-file"], s.inserted),
            rule("Deleted", ["markup.deleted", "punctuation.definition.deleted", "meta.diff.header.from-file"], s.deleted),
            rule("Changed", ["markup.changed", "punctuation.definition.changed"], s.changed),
            rule("Diff range", ["meta.diff.range", "meta.diff.header"], s.info),
        ]
    }

    static func semanticTokenColors(for s: SyntaxPalette) -> [String: Any] {
        var colors: [String: Any] = [
            "comment": ["foreground": s.comment.hex, "italic": true],
            "keyword": s.keyword.hex,
            "modifier": s.keyword.hex,
            "selfKeyword": s.keyword.hex,
            "selfParameter": s.keyword.hex,
            "string": s.string.hex,
            "number": s.constant.hex,
            "enumMember": s.constant.hex,
            "builtinConstant": s.constant.hex,
            "regexp": s.special.hex,
            "operator": s.operator.hex,
            "function": s.function.hex,
            "method": s.function.hex,
            "macro": s.function.hex,
            "variable": s.variable.hex,
            "parameter": s.variable.hex,
            "property": s.property.hex,
            "decorator": s.attribute.hex,
            "*.deprecated": ["strikethrough": true],
        ]
        for type in ["type", "class", "enum", "interface", "struct", "typeParameter", "namespace", "builtinType"] {
            colors[type] = s.type.hex
        }
        return colors
    }
