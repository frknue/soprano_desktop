import Foundation

/// fzf colours as a shell snippet the user sources from `.zshrc` or `.bashrc`. It picks the
/// light or dark spec from macOS's appearance when the shell starts and appends it to
/// `FZF_DEFAULT_OPTS`, replacing the block a previous source added.
public enum FzfColors {
    /// `shell/fzf.sh` (relative to `~/.config/soprano-desktop`).
    public static func files(for pair: ThemePair) -> [GeneratedFile] {
        [GeneratedFile(path: "shell/fzf.sh", contents: snippet(for: pair))]
    }

    /// fzf `--color=` spec for one palette. The accent marks only the pointer and the matched
    /// characters; the current line gets Folio's selection.
    public static func colorSpec(for palette: Palette) -> String {
        let slots: [(String, RGB)] = [
            ("fg", palette.textPrimary),
            ("bg", palette.bgBase),
            ("hl", palette.accent),
            ("fg+", palette.textPrimary),
            ("bg+", selection(for: palette)),
            ("hl+", palette.accent),
            ("gutter", palette.bgBase),
            ("query", palette.textPrimary),
            ("disabled", palette.textMuted),
            ("info", palette.textMuted),
            ("border", palette.borderStrong),
            ("separator", palette.borderSubtle),
            ("scrollbar", palette.borderStrong),
            ("label", palette.textMuted),
            ("prompt", palette.textMuted),
            ("pointer", palette.accent),
            ("marker", palette.textPrimary),
            ("spinner", palette.textMuted),
            ("header", palette.textMuted),
        ]
        return "--color=" + slots.map { "\($0.0):\($0.1.hex)" }.joined(separator: ",")
    }

    private static func selection(for palette: Palette) -> RGB {
        palette.isLight ? palette.terminal.selectionBackground : palette.selection
    }

    private static func snippet(for pair: ThemePair) -> String {
        """
        # fzf colours for \(ThemeNames.light) (\(pair.light.name)) and \(ThemeNames.dark) (\(pair.dark.name)).
        # Generated by Soprano Desktop. Edits are overwritten when Soprano's theme changes.
        # Source it from ~/.zshrc or ~/.bashrc after setting FZF_DEFAULT_OPTS:
        #   [ -f ~/.config/soprano-desktop/shell/fzf.sh ] && . ~/.config/soprano-desktop/shell/fzf.sh

        # Drop the block an earlier source added, wherever it sits in FZF_DEFAULT_OPTS.
        if [ -n "${SOPRANO_FZF_COLOR_OPTS-}" ]; then
          case " ${FZF_DEFAULT_OPTS-} " in
            *" $SOPRANO_FZF_COLOR_OPTS "*)
              _soprano_fzf_opts=" ${FZF_DEFAULT_OPTS-} "
              _soprano_fzf_opts="${_soprano_fzf_opts%%" $SOPRANO_FZF_COLOR_OPTS "*} ${_soprano_fzf_opts#*" $SOPRANO_FZF_COLOR_OPTS "}"
              _soprano_fzf_opts="${_soprano_fzf_opts# }"
              FZF_DEFAULT_OPTS="${_soprano_fzf_opts% }"
              unset _soprano_fzf_opts
              ;;
          esac
        fi

        if [ "$(defaults read -g AppleInterfaceStyle 2>/dev/null)" = "Dark" ]; then
          SOPRANO_FZF_COLOR_OPTS='\(colorSpec(for: pair.dark))'
        else
          SOPRANO_FZF_COLOR_OPTS='\(colorSpec(for: pair.light))'
        fi

        FZF_DEFAULT_OPTS="${FZF_DEFAULT_OPTS:+$FZF_DEFAULT_OPTS }$SOPRANO_FZF_COLOR_OPTS"
        export FZF_DEFAULT_OPTS SOPRANO_FZF_COLOR_OPTS

        """
    }
}
