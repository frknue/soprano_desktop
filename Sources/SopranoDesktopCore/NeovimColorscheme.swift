        let selection = p.selection

        var result: [(group: String, highlight: Highlight)] = []
        func set(_ group: String, _ highlight: Highlight) {
            result.append((group, highlight))
        }
        func set(_ groups: [String], _ highlight: Highlight) {
            for group in groups { result.append((group, highlight)) }
        }
