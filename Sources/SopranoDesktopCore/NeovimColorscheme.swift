        set(["SignColumn", "FoldColumn"], Highlight(fg: p.gray, bg: bg))
        set(["Visual", "VisualNOS"], Highlight(bg: selection))
        set("Search", Highlight(fg: fg, bg: searchWash))
        set(["IncSearch", "CurSearch", "Substitute"], Highlight(fg: bg, bg: p.accent, bold: true))
        set("MatchParen", Highlight(fg: p.accent, bold: true))
        set("Pmenu", Highlight(fg: fg, bg: p.bgRaised))
        set("PmenuSel", Highlight(fg: fg, bg: selection, bold: true))
        set(["PmenuKind", "PmenuExtra"], Highlight(fg: muted, bg: p.bgRaised))
        set(["PmenuKindSel", "PmenuExtraSel"], Highlight(fg: muted, bg: selection))
        set("PmenuMatch", Highlight(fg: p.accent, bg: p.bgRaised, bold: true))
        set("PmenuMatchSel", Highlight(fg: p.accent, bg: selection, bold: true))
        set("PmenuSbar", Highlight(bg: p.bgPanel))
        set("PmenuThumb", Highlight(bg: p.borderStrong))
        set("StatusLine", Highlight(fg: fg, bg: p.bgPanel))
        set("StatusLineNC", Highlight(fg: muted, bg: p.bgPanel))
        set("TabLine", Highlight(fg: muted, bg: p.bgPanel))
        set("TabLineFill", Highlight(bg: p.bgPanel))
        set("TabLineSel", Highlight(fg: fg, bg: bg, bold: true))
        set(["WinSeparator", "VertSplit"], Highlight(fg: p.borderStrong))
        set("Folded", Highlight(fg: muted, bg: p.bgPanel, italic: true))
        set(["NonText", "Whitespace", "SpecialKey", "EndOfBuffer"], Highlight(fg: p.borderStrong))
        set("Directory", Highlight(fg: p.blue))
        set("Title", Highlight(fg: fg, bold: true))
        set(["Question", "MoreMsg"], Highlight(fg: p.success))
        set("ModeMsg", Highlight(fg: fg, bold: true))
        set("MsgArea", Highlight(fg: fg))
        set("WarningMsg", Highlight(fg: s.warning))
        set("ErrorMsg", Highlight(fg: s.error))
        set("Conceal", Highlight(fg: muted))
        set("SpellBad", Highlight(sp: s.error, undercurl: true))
        set("SpellCap", Highlight(sp: s.warning, undercurl: true))
        set("SpellLocal", Highlight(sp: s.info, undercurl: true))
        set("SpellRare", Highlight(sp: s.hint, undercurl: true))
        set("DiffAdd", Highlight(bg: wash(s.inserted, 0.16)))
        set("DiffChange", Highlight(bg: wash(s.changed, 0.1)))
        set("DiffDelete", Highlight(fg: s.deleted, bg: wash(s.deleted, 0.12)))
        set("DiffText", Highlight(bg: wash(s.changed, 0.26)))
        set("QuickFixLine", Highlight(bg: selection, bold: true))
        set("WildMenu", Highlight(fg: fg, bg: selection, bold: true))
        set("WinBar", Highlight(fg: fg, bg: bg, bold: true))
        set("WinBarNC", Highlight(fg: muted, bg: bg))

        // Legacy syntax
        set("Comment", Highlight(fg: s.comment, italic: true))
        set("Constant", Highlight(fg: s.constant))
        set(["String", "Character"], Highlight(fg: s.string))
        set(["Number", "Boolean", "Float"], Highlight(fg: s.constant))
        set("Identifier", Highlight(fg: s.variable))
        set("Function", Highlight(fg: s.function))
        set(
            ["Statement", "Conditional", "Repeat", "Label", "Keyword", "Exception",
             "PreProc", "Include", "Define", "Macro", "PreCondit", "StorageClass"],
            Highlight(fg: s.keyword)
        )
        set("Operator", Highlight(fg: s.operator))
        set(["Type", "Structure", "Typedef"], Highlight(fg: s.type))
        set(["Special", "SpecialChar", "Debug"], Highlight(fg: s.special))
        set("Tag", Highlight(fg: s.tag))
        set("Delimiter", Highlight(fg: s.punctuation))
        set("SpecialComment", Highlight(fg: s.comment, italic: true))
        set("Underlined", Highlight(fg: s.function, underline: true))
        set("Ignore", Highlight(fg: muted))
        set("Error", Highlight(fg: s.error))
        set("Todo", Highlight(fg: s.warning, bold: true))
        set("Added", Highlight(fg: s.inserted))
        set("Changed", Highlight(fg: s.changed))
        set("Removed", Highlight(fg: s.deleted))

        // Tree-sitter
        set(["@comment", "@comment.documentation"], Highlight(fg: s.comment, italic: true))
        set("@comment.error", Highlight(fg: s.error, bold: true))
        set(["@comment.warning", "@comment.todo"], Highlight(fg: s.warning, bold: true))
        set("@comment.note", Highlight(fg: s.info, bold: true))
        set(
            ["@keyword", "@keyword.function", "@keyword.return", "@keyword.operator",
             "@keyword.import", "@keyword.conditional", "@keyword.conditional.ternary",
             "@keyword.repeat", "@keyword.exception", "@keyword.modifier", "@keyword.type",
             "@keyword.coroutine", "@keyword.directive", "@keyword.directive.define",
             "@keyword.debug", "@label"],
            Highlight(fg: s.keyword)
        )
        set(["@string", "@string.documentation", "@character"], Highlight(fg: s.string))
        set(
            ["@string.escape", "@string.regexp", "@string.special", "@string.special.symbol",
             "@string.special.path", "@character.special"],
            Highlight(fg: s.special)
        )
        set("@string.special.url", Highlight(fg: s.function, underline: true))
        set(
            ["@number", "@number.float", "@boolean", "@constant", "@constant.builtin",
             "@constant.macro"],
            Highlight(fg: s.constant)
        )
        set(
            ["@function", "@function.call", "@function.builtin", "@function.macro",
             "@function.method", "@function.method.call", "@method", "@method.call"],
            Highlight(fg: s.function)
        )
        set("@constructor", Highlight(fg: s.type))
        set(
            ["@type", "@type.builtin", "@type.definition", "@module", "@module.builtin",
             "@namespace"],
            Highlight(fg: s.type)
        )
        set("@type.qualifier", Highlight(fg: s.keyword))
        set("@variable", Highlight(fg: s.variable))
        set("@variable.builtin", Highlight(fg: s.keyword))
        set(["@variable.parameter", "@variable.parameter.builtin"], Highlight(fg: s.variable, italic: true))
        set(["@variable.member", "@property", "@field"], Highlight(fg: s.property))
        set("@attribute", Highlight(fg: s.attribute))
        set("@operator", Highlight(fg: s.operator))
        set(["@punctuation", "@punctuation.delimiter", "@punctuation.bracket"], Highlight(fg: s.punctuation))
        set("@punctuation.special", Highlight(fg: s.special))
        set(["@tag", "@tag.builtin"], Highlight(fg: s.tag))
        set("@tag.attribute", Highlight(fg: s.attribute))
        set("@tag.delimiter", Highlight(fg: s.punctuation))
        set(
            ["@markup.heading", "@markup.heading.1", "@markup.heading.2", "@markup.heading.3",
             "@markup.heading.4", "@markup.heading.5", "@markup.heading.6"],
            Highlight(fg: s.function, bold: true)
        )
        set("@markup.strong", Highlight(bold: true))
        set("@markup.italic", Highlight(italic: true))
        set("@markup.strikethrough", Highlight(strikethrough: true))
        set("@markup.underline", Highlight(underline: true))
        set(["@markup.link", "@markup.link.url"], Highlight(fg: s.function, underline: true))
        set("@markup.link.label", Highlight(fg: s.special))
        set(["@markup.raw", "@markup.raw.block"], Highlight(fg: s.string))
        set("@markup.quote", Highlight(fg: s.comment, italic: true))
        set(["@markup.list", "@markup.list.checked", "@markup.list.unchecked"], Highlight(fg: s.special))
        set("@markup.math", Highlight(fg: s.special))
        set("@diff.plus", Highlight(fg: s.inserted))
        set("@diff.minus", Highlight(fg: s.deleted))
        set("@diff.delta", Highlight(fg: s.changed))

        // LSP semantic tokens
        set(
            ["@lsp.type.class", "@lsp.type.enum", "@lsp.type.interface", "@lsp.type.struct",
             "@lsp.type.type", "@lsp.type.typeParameter", "@lsp.type.namespace"],
            .link("@type")
        )
        set(["@lsp.type.function", "@lsp.type.method"], .link("@function"))
        set("@lsp.type.keyword", .link("@keyword"))
        set("@lsp.type.parameter", .link("@variable.parameter"))
        set("@lsp.type.property", .link("@property"))
        set("@lsp.type.variable", .link("@variable"))
        set("@lsp.type.enumMember", .link("@constant"))
        set("@lsp.type.macro", .link("@constant.macro"))
        set("@lsp.type.decorator", .link("@attribute"))
        set("@lsp.type.comment", .link("@comment"))
        set("@lsp.type.string", .link("@string"))
        set("@lsp.type.number", .link("@number"))
        set("@lsp.type.operator", .link("@operator"))
        set("@lsp.mod.deprecated", Highlight(strikethrough: true))

        // Diagnostics
        let diagnostics: [(String, RGB)] = [
            ("Error", s.error), ("Warn", s.warning), ("Info", s.info), ("Hint", s.hint), ("Ok", p.success),
        ]
        for (kind, color) in diagnostics {
            set("Diagnostic\(kind)", Highlight(fg: color))
            set("DiagnosticUnderline\(kind)", Highlight(sp: color, undercurl: true))
            set("DiagnosticVirtualText\(kind)", Highlight(fg: color, bg: wash(color, 0.08)))
            set("DiagnosticSign\(kind)", Highlight(fg: color))
            set("DiagnosticFloating\(kind)", Highlight(fg: color))
        }
        set("DiagnosticDeprecated", Highlight(sp: muted, strikethrough: true))
        set("DiagnosticUnnecessary", Highlight(fg: muted))
        set(["LspReferenceText", "LspReferenceRead", "LspReferenceTarget"], Highlight(bg: reference))
        set("LspReferenceWrite", Highlight(bg: reference, bold: true))
        set(["LspInlayHint", "LspCodeLens"], Highlight(fg: p.gray, italic: true))
        set("LspSignatureActiveParameter", Highlight(bold: true, underline: true))

        // Git
        set(["GitSignsAdd", "diffAdded"], Highlight(fg: s.inserted))
        set(["GitSignsChange", "diffChanged"], Highlight(fg: s.changed))
        set(["GitSignsDelete", "diffRemoved"], Highlight(fg: s.deleted))

        // Plugins
        set(["TelescopeNormal", "TelescopePromptNormal"], Highlight(fg: fg, bg: p.bgRaised))
        set(["TelescopeBorder", "TelescopePromptBorder"], Highlight(fg: p.borderStrong, bg: p.bgRaised))
        set("TelescopeTitle", Highlight(fg: fg, bold: true))
        set("TelescopeSelection", Highlight(fg: fg, bg: selection, bold: true))
        set("TelescopeSelectionCaret", Highlight(fg: p.accent, bg: selection))
        set("TelescopeMatching", Highlight(fg: p.accent, bold: true))
        set("TelescopePromptPrefix", Highlight(fg: p.accent))
        set("NvimTreeNormal", Highlight(fg: fg, bg: p.bgPanel))
        set("NvimTreeWinSeparator", Highlight(fg: p.borderSubtle, bg: p.bgPanel))
        set(["NvimTreeFolderName", "NvimTreeFolderIcon", "NvimTreeOpenedFolderName"], Highlight(fg: p.blue))
        set("NvimTreeRootFolder", Highlight(fg: muted, bold: true))
        set("NvimTreeGitDirty", Highlight(fg: s.changed))
        set("NvimTreeGitNew", Highlight(fg: s.inserted))
        set("NvimTreeGitDeleted", Highlight(fg: s.deleted))
        set("MiniStatuslineModeNormal", Highlight(fg: bg, bg: fg, bold: true))
        set("MiniStatuslineModeInsert", Highlight(fg: bg, bg: p.success, bold: true))
        set("MiniStatuslineModeVisual", Highlight(fg: bg, bg: p.blue, bold: true))
        set("MiniStatuslineModeReplace", Highlight(fg: bg, bg: p.danger, bold: true))
        set("MiniStatuslineModeCommand", Highlight(fg: bg, bg: p.yellow, bold: true))
        set("MiniStatuslineModeOther", Highlight(fg: bg, bg: p.gray, bold: true))
        set(["MiniStatuslineDevinfo", "MiniStatuslineFileinfo"], Highlight(fg: fg, bg: p.bgOverlay))
        set(["MiniStatuslineFilename", "MiniStatuslineInactive"], Highlight(fg: muted, bg: p.bgPanel))
        set("WhichKey", Highlight(fg: s.function))
        set("WhichKeyGroup", Highlight(fg: s.keyword))
        set("WhichKeyDesc", Highlight(fg: fg))
        set("WhichKeySeparator", Highlight(fg: muted))
        set(["WhichKeyFloat", "WhichKeyNormal"], Highlight(fg: fg, bg: p.bgRaised))
        set("WhichKeyBorder", Highlight(fg: p.borderStrong, bg: p.bgRaised))
        set("LazyNormal", Highlight(fg: fg, bg: p.bgRaised))
        set("LazyButton", Highlight(fg: fg, bg: p.bgOverlay))
        set(["LazyButtonActive", "LazyH1"], Highlight(fg: bg, bg: fg, bold: true))
        set("LazyH2", Highlight(fg: fg, bold: true))
        set("LazySpecial", Highlight(fg: s.special))
        set("LazyProgressDone", Highlight(fg: p.success))
        set("LazyProgressTodo", Highlight(fg: p.borderStrong))

        return result
    }
