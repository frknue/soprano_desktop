import Foundation

/// The `soprano` Neovim colorscheme: one Lua file holding the light and the dark palette,
/// choosing between them by `'background'` and re-applying itself when `'background'`
/// changes, so Neovim follows the terminal's (and the desktop's) appearance.
public enum NeovimColorscheme {
    public static let name = "soprano"

    /// One file: "colors/soprano.lua" (installed under ~/.local/share/nvim/site, which is on
    /// Neovim's default runtimepath).
    public static func files(for pair: ThemePair) -> [GeneratedFile] {
        [GeneratedFile(path: "colors/\(name).lua", contents: lua(for: pair))]
    }

    static func lua(for pair: ThemePair) -> String {
        var lines = [
            "-- Soprano colorscheme for Neovim: \(pair.light.name) when 'background' is light, \(pair.dark.name) when it is dark.",
            "-- Generated by Soprano Desktop and overwritten whenever the Soprano theme changes; edits here are lost.",
            "",
            "local palettes = {}",
            "",
        ]
        lines += paletteTable(key: "light", palette: pair.light)
        lines.append("")
        lines += paletteTable(key: "dark", palette: pair.dark)
        lines.append("")
        lines.append(contentsOf: [
            "local function apply()",
            "  local palette = vim.o.background == \"light\" and palettes.light or palettes.dark",
            "  vim.cmd(\"highlight clear\")",
            "  if vim.fn.exists(\"syntax_on\") == 1 then",
            "    vim.cmd(\"syntax reset\")",
            "  end",
            "  vim.o.termguicolors = true",
            "  vim.g.colors_name = \"\(name)\"",
            "  for index, color in ipairs(palette.terminal) do",
            "    vim.g[\"terminal_color_\" .. (index - 1)] = color",
            "  end",
            "  for group, spec in pairs(palette.groups) do",
            "    vim.api.nvim_set_hl(0, group, spec)",
            "  end",
            "end",
            "",
            "apply()",
            "",
            "vim.api.nvim_create_autocmd(\"OptionSet\", {",
            "  group = vim.api.nvim_create_augroup(\"SopranoColorscheme\", { clear = true }),",
            "  pattern = \"background\",",
            "  callback = function()",
            "    if vim.g.colors_name ~= \"\(name)\" then",
            "      return",
            "    end",
            "    apply()",
            "    vim.api.nvim_exec_autocmds(\"ColorScheme\", { pattern = \"\(name)\", modeline = false })",
            "  end,",
            "})",
        ])
        return lines.joined(separator: "\n") + "\n"
    }

    private static func paletteTable(key: String, palette: Palette) -> [String] {
        var lines = [
            "palettes.\(key) = {",
            "  name = \(luaString(palette.name)),",
            "  terminal = {",
        ]
        lines += palette.terminal.ansi.map { "    \"\($0.hex)\"," }
        lines.append("  },")
        lines.append("  groups = {")
        lines += highlights(for: palette).map { "    [\"\($0.group)\"] = \($0.highlight.lua)," }
        lines.append("  },")
        lines.append("}")
        return lines
    }

    private static func luaString(_ text: String) -> String {
        var escaped = ""
        for character in text {
            switch character {
            case "\\": escaped += "\\\\"
            case "\"": escaped += "\\\""
            case "\n": escaped += "\\n"
            case "\r": escaped += "\\r"
            default: escaped.append(character)
            }
        }
        return "\"\(escaped)\""
    }

    /// One `nvim_set_hl` spec.
    struct Highlight: Equatable {
        var link: String?
        var fg: RGB?
        var bg: RGB?
        var sp: RGB?
        var bold = false
        var italic = false
        var underline = false
        var undercurl = false
        var strikethrough = false
        var reverse = false

        static func link(_ group: String) -> Highlight {
            Highlight(link: group)
        }

        var lua: String {
            var fields: [String] = []
            if let link { fields.append("link = \"\(link)\"") }
            if let fg { fields.append("fg = \"\(fg.hex)\"") }
            if let bg { fields.append("bg = \"\(bg.hex)\"") }
            if let sp { fields.append("sp = \"\(sp.hex)\"") }
            if bold { fields.append("bold = true") }
            if italic { fields.append("italic = true") }
            if underline { fields.append("underline = true") }
            if undercurl { fields.append("undercurl = true") }
            if strikethrough { fields.append("strikethrough = true") }
            if reverse { fields.append("reverse = true") }
            return fields.isEmpty ? "{}" : "{ " + fields.joined(separator: ", ") + " }"
        }
    }

    static func highlights(for p: Palette) -> [(group: String, highlight: Highlight)] {
        let s = SyntaxPalette(p)
        let bg = p.bgBase
        let fg = p.textPrimary
