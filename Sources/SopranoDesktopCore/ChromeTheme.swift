import Foundation

/// Chrome theme extensions, one unpacked extension per slot, loaded by hand from
/// `chrome://extensions` ("Load unpacked"). Chrome themes cannot follow the system
/// appearance, so the user picks the slot they want.
public enum ChromeTheme {
    /// `chrome/soprano-light/manifest.json` and `chrome/soprano-dark/manifest.json`.
    public static func files(for pair: ThemePair) -> [GeneratedFile] {
        [
            GeneratedFile(
                path: "chrome/\(ThemeNames.lightSlug)/manifest.json",
                contents: manifest(for: pair.light, name: ThemeNames.light)
            ),
            GeneratedFile(
                path: "chrome/\(ThemeNames.darkSlug)/manifest.json",
                contents: manifest(for: pair.dark, name: ThemeNames.dark)
            ),
        ]
    }

    /// A Manifest V3 theme: the tab strip on the panel colour, the active tab, toolbar and
    /// new-tab page on the paper colour, the omnibox raised above it. Colour keys are the
    /// overwritable ones in Chromium's `browser_theme_pack.cc`.
    public static func manifest(for palette: Palette, name: String) -> String {
        let frame = palette.bgPanel
        let colors: [String: RGB] = [
            "frame": frame,
            "frame_inactive": frame.mixed(with: palette.bgBase, amount: 0.5),
            "frame_incognito": palette.bgOverlay,
            "frame_incognito_inactive": palette.bgOverlay.mixed(with: palette.bgBase, amount: 0.5),
            "background_tab": frame,
            "background_tab_inactive": frame.mixed(with: palette.bgBase, amount: 0.5),
            "toolbar": palette.bgBase,
            "tab_text": palette.textPrimary,
            "tab_background_text": palette.textMuted,
            "tab_background_text_inactive": palette.textMuted,
            "bookmark_text": palette.textPrimary,
            "toolbar_text": palette.textPrimary,
            "toolbar_button_icon": palette.textMuted,
            "omnibox_background": palette.bgRaised,
            "omnibox_text": palette.textPrimary,
            "ntp_background": palette.bgBase,
            "ntp_text": palette.textPrimary,
            "ntp_link": palette.blue,
            "button_background": frame,
        ]
        let object: [String: Any] = [
            "manifest_version": 3,
            "name": name,
            "version": "1.0",
            "description": "\(name) (\(palette.name)), generated by Soprano Desktop.",
            "theme": [
                "colors": colors.mapValues(components),
                "properties": ["ntp_background_alignment": "bottom"],
            ] as [String: Any],
        ]
        let data = try! JSONSerialization.data(
            withJSONObject: object,
            options: [.sortedKeys, .prettyPrinted, .withoutEscapingSlashes]
        )
        return String(decoding: data, as: UTF8.self) + "\n"
    }

    private static func components(_ colour: RGB) -> [Int] {
        [colour.red, colour.green, colour.blue].map { Int(($0 * 255).rounded()) }
    }
}
