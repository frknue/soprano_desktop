import Foundation

/// Ghostty theme files for the light and dark slot. Ghostty reads them from `themes/` in its
/// config directory and switches between them with `theme = light:…,dark:…`.
public enum GhosttyTheme {
    /// `themes/soprano-light` and `themes/soprano-dark` (relative to the Ghostty config dir).
    public static func files(for pair: ThemePair) -> [GeneratedFile] {
        [
            GeneratedFile(path: "themes/" + ThemeNames.lightSlug, contents: theme(for: pair.light)),
            GeneratedFile(path: "themes/" + ThemeNames.darkSlug, contents: theme(for: pair.dark)),
        ]
    }

    /// One Ghostty theme file: the terminal colours, the 16 ANSI slots, a sienna caret and
    /// Folio's selection (a sienna wash on light palettes, the neutral fill on dark ones).
    public static func theme(for palette: Palette) -> String {
        let terminal = palette.terminal
        var lines = [
            "# \(palette.name), generated by Soprano Desktop.",
            "# Edits are overwritten when Soprano's theme changes.",
            "",
            "background = \(terminal.background.hex)",
            "foreground = \(terminal.foreground.hex)",
            "cursor-color = \(palette.accent.hex)",
            "cursor-text = \(terminal.cursorAccent.hex)",
            "selection-background = \(selectionBackground(for: palette).hex)",
            "selection-foreground = \(terminal.foreground.hex)",
            "split-divider-color = \(palette.borderStrong.hex)",
        ]
        for (index, colour) in terminal.ansi.enumerated() {
            lines.append("palette = \(index)=\(colour.hex)")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// The value for Ghostty's `theme` key that follows macOS: `light:soprano-light,dark:soprano-dark`.
    public static let themeSetting = "light:\(ThemeNames.lightSlug),dark:\(ThemeNames.darkSlug)"

    private static func selectionBackground(for palette: Palette) -> RGB {
        palette.isLight ? palette.terminal.selectionBackground : palette.selection
    }
}
