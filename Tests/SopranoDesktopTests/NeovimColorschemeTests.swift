import AppKit
import Testing
@testable import SopranoDesktopCore

struct NeovimColorschemeTests {
    private static func lua(_ pair: ThemePair = TestPalettes.folio) throws -> String {
        let files = NeovimColorscheme.files(for: pair)
        #expect(files.map(\.path) == ["colors/soprano.lua"])
        return try #require(files.first).contents
    }

    /// The `palettes.light = { … }` or `palettes.dark = { … }` block of the generated Lua.
    private static func section(_ key: String, of lua: String) throws -> Substring {
        let start = try #require(lua.range(of: "palettes.\(key) = {\n"))
        let end = try #require(lua.range(of: "\n}\n", range: start.upperBound..<lua.endIndex))
        return lua[start.upperBound..<end.lowerBound]
    }

    @Test func theFileIsTheSopranoColorschemeAndSaysItIsGeneratedAndOverwritten() throws {
        let lua = try Self.lua()
        let firstLines = lua.split(separator: "\n").prefix(2)
        #expect(firstLines.allSatisfy { $0.hasPrefix("--") })
        #expect(firstLines.joined().contains("Generated by Soprano Desktop"))
        #expect(firstLines.joined().contains("overwritten"))
        #expect(lua.contains("vim.g.colors_name = \"soprano\""))
        #expect(lua.contains("vim.o.termguicolors = true"))
    }

    @Test func bothPalettesArePresentAndTheSchemePicksOneByBackground() throws {
        let lua = try Self.lua()
        let light = try Self.section("light", of: lua)
        let dark = try Self.section("dark", of: lua)
        #expect(lua.contains("vim.o.background == \"light\" and palettes.light or palettes.dark"))
        #expect(light.contains("[\"Normal\"] = { fg = \"#2b2620\", bg = \"#f6f2ea\" },"))
        #expect(dark.contains("[\"Normal\"] = { fg = \"#e2dacb\", bg = \"#1d1b18\" },"))
        #expect(light.contains("\"#8a3f78\","))
        #expect(dark.contains("\"#c191b8\","))
    }

    @Test func changingBackgroundReappliesOnlyWhileSopranoIsTheActiveColorscheme() throws {
        let lua = try Self.lua()
        let autocmd = try #require(lua.range(of: "vim.api.nvim_create_autocmd(\"OptionSet\""))
        let callback = lua[autocmd.lowerBound...]
        #expect(callback.contains("pattern = \"background\""))
        #expect(callback.contains("if vim.g.colors_name ~= \"soprano\" then"))
        #expect(callback.contains("apply()"))
    }

    @Test func theCursorWearsTheAccentWhileSyntaxComesFromTheSharedSyntaxPalette() throws {
        let lua = try Self.lua()
        let light = try Self.section("light", of: lua)
        let syntax = SyntaxPalette(TestPalettes.paper)
        #expect(light.contains("[\"Cursor\"] = { fg = \"#f6f2ea\", bg = \"#a34a17\" },"))
        #expect(light.contains("[\"Comment\"] = { fg = \"\(syntax.comment.hex)\", italic = true },"))
        #expect(light.contains("[\"@keyword\"] = { fg = \"\(syntax.keyword.hex)\" },"))
        #expect(light.contains("[\"@function\"] = { fg = \"\(syntax.function.hex)\" },"))
        #expect(!light.contains("[\"@keyword\"] = { fg = \"\(TestPalettes.paper.accent.hex)\""))
    }

    @Test func lightSelectionIsASiennaWashAndDarkSelectionIsTheNeutralFill() throws {
        let lua = try Self.lua()
        let light = try Self.section("light", of: lua)
        let dark = try Self.section("dark", of: lua)
        #expect(light.contains("[\"Visual\"] = { bg = \"\(TestPalettes.paper.selection.hex)\" },"))
        #expect(dark.contains("[\"Visual\"] = { bg = \"\(TestPalettes.ink.selection.hex)\" },"))
    }

    @Test func everyHighlightGroupIsDefinedOnceSoNoneSilentlyOverridesAnother() {
        let groups = NeovimColorscheme.highlights(for: TestPalettes.paper).map(\.group)
        #expect(Set(groups).count == groups.count)
    }

    @Test func aPinnedPairStillDefinesBothBackgroundsWithTheSamePalette() throws {
        let lua = try Self.lua(ThemePair(light: TestPalettes.ink, dark: TestPalettes.ink))
        #expect(try Self.section("light", of: lua) == Self.section("dark", of: lua))
        #expect(try Self.section("light", of: lua).contains("bg = \"#1d1b18\""))
    }
}
